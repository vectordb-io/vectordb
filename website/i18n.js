  const supported = language => Object.hasOwn(messages, language);
  let language = 'en';
  try {
    const saved = localStorage.getItem(storageKey);
    if (supported(saved)) language = saved;
  } catch { /* Language switching also works when storage is unavailable. */ }

  const t = key => messages[language][key] ?? messages.en[key] ?? key;
  function applyLanguage(next, persist = false) {
    language = supported(next) ? next : 'en';
    document.documentElement.lang = language;
    document.querySelectorAll('[data-i18n]').forEach(element => {
      // Only trusted strings from the dictionary above are interpreted as markup.
      element.innerHTML = t(element.dataset.i18n);
    });
    for (const attribute of ['aria-label', 'content']) {
      document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
        element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
      });
    }
    document.querySelector('#language').value = language;
    if (persist) {
      try { localStorage.setItem(storageKey, language); } catch { /* Optional persistence. */ }
    }
    window.dispatchEvent(new Event('languagechange'));
  }
  window.VectorDBI18n = { t };
  document.querySelector('#language').addEventListener('change', event => applyLanguage(event.target.value, true));
